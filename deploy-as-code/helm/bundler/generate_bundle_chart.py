#!/usr/bin/env python3
"""Generate a merged "modulith bundle" Helm chart from a digit3 bundle manifest.

The same <bundle>.package.yaml that drives digit3's generate_bundle.py (which
composes the application jar) drives this generator on the DevOps side: the
manifest's service list says which per-service Helm charts get merged into one
bundle chart.

    python3 generate_bundle_chart.py --manifest /path/to/dev-bundle.package.yaml

For each service the generator resolves the chart directory (<name>-java, then
<name>, across every charts/* group), renders it with `helm template` so all
`env: |` template strings resolve exactly as they would at deploy time, and
harvests the container env and the db-migration init container. Envs are merged
under the policy in merge-rules.yaml (optionally extended by a `helm:` section
in the manifest); same-name-different-value conflicts that no rule resolves are
reported and first-in-manifest-order wins.

The generated chart differs from the per-service charts in one deliberate way:
env is a MAP (name -> {value|valueFrom}), not a string block. Helm deep-merges
maps from the environment values file, so any single variable can be overridden
per environment under the bundle's own block (the per-service charts' string
blocks can only be replaced wholesale). Setting a variable to null removes it.

Everything under the output chart is generator-owned; edit the manifest or
merge-rules.yaml and re-run.
"""

import argparse
import copy
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
DEFAULT_CHARTS_ROOT = HERE.parent / "charts"
CHART_NAME_CANDIDATES = ("{name}-java", "{name}")

GENERATED_BANNER = (
    "# GENERATED by deploy-as-code/helm/bundler/generate_bundle_chart.py from {manifest} —\n"
    "# edit the manifest or bundler/merge-rules.yaml and re-run; do not edit this file.\n"
)


def die(msg):
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f)


# ── chart resolution ─────────────────────────────────────────────────────────

def resolve_chart(charts_root, service_name):
    """Find the chart directory for a manifest service name."""
    for group in sorted(p for p in charts_root.iterdir() if p.is_dir()):
        for cand in CHART_NAME_CANDIDATES:
            chart_dir = group / cand.format(name=service_name)
            if (chart_dir / "Chart.yaml").exists():
                return chart_dir
    return None


# ── rendering member charts ──────────────────────────────────────────────────

def render_deployment(chart_dir, common_dir, scratch_root):
    """helm-template a member chart in a scratch copy and return its Deployment."""
    scratch = scratch_root / chart_dir.name
    shutil.copytree(chart_dir, scratch)
    # Vendor the common library chart so `helm template` needs no repo access.
    shutil.copytree(common_dir, scratch / "charts" / "common")
    cmd = [
        "helm", "template", chart_dir.name, str(scratch),
        "-s", "templates/deployment.yaml",
        "--set", "image.tag=SCRATCH",
        "--set", "initContainers.dbMigration.image.tag=SCRATCH",
        "--set", "global.domain=scratch.local",
        "--set", "global.setup=fullsetup",
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        die(f"helm template failed for {chart_dir.name}:\n{res.stderr}")
    for doc in yaml.safe_load_all(res.stdout):
        if doc and doc.get("kind") == "Deployment":
            return doc
    die(f"no Deployment rendered for {chart_dir.name}")


def extract_main_env(deployment, chart_name):
    containers = deployment["spec"]["template"]["spec"].get("containers", [])
    main = next((c for c in containers if c.get("name") == chart_name), None)
    if main is None:
        main = containers[0]
    return main.get("env") or []


def extract_db_migration(deployment):
    inits = deployment["spec"]["template"]["spec"].get("initContainers") or []
    return next((c for c in inits if c.get("name") == "db-migration"), None)


# ── env merge machinery ──────────────────────────────────────────────────────

def env_list_to_specs(env_list):
    """[{name, value|valueFrom}] -> ordered [(name, spec-dict)]."""
    out = []
    for e in env_list:
        spec = {k: v for k, v in e.items() if k != "name"}
        out.append((e["name"], spec))
    return out


def canon(spec):
    return json.dumps(spec, sort_keys=True)


class MergePolicy:
    def __init__(self, rules, manifest_helm):
        rules = copy.deepcopy(rules or {})
        manifest_helm = copy.deepcopy(manifest_helm or {})
        self.drop_exact = {}
        self.drop_patterns = []
        for entry in (rules.get("drop") or []) + (manifest_helm.get("drop") or []):
            reason = entry.get("reason", "")
            if "name" in entry:
                self.drop_exact[entry["name"]] = reason
            elif "pattern" in entry:
                self.drop_patterns.append((re.compile(entry["pattern"]), reason))
        self.resolve = dict(rules.get("resolve") or {})
        self.resolve.update(manifest_helm.get("resolve") or {})
        self.contract_env = dict(rules.get("contractEnv") or {})
        self.contract_env.update(manifest_helm.get("contractEnv") or {})

    def drop_reason(self, name):
        if name in self.drop_exact:
            return self.drop_exact[name] or "dropped by rule"
        for rx, reason in self.drop_patterns:
            if rx.search(name):
                return reason or f"dropped by pattern {rx.pattern}"
        return None


def is_loopback(spec, bundled_chart_names):
    """Env sourced from egov-service-host for a bundled service, or a literal
    URL to a bundled service — the bundle jar already rewires these to
    localhost, and an env var would silently win over that property."""
    cm = (spec.get("valueFrom") or {}).get("configMapKeyRef") or {}
    if cm.get("name") == "egov-service-host" and cm.get("key") in bundled_chart_names:
        return True
    value = spec.get("value")
    if isinstance(value, str):
        for chart in bundled_chart_names:
            if re.search(rf"https?://{re.escape(chart)}([.:/]|$)", value):
                return True
    return False


def merge_envs(per_service_envs, policy, bundled_chart_names, report):
    """per_service_envs: [(service_name, [(env_name, spec)])] in manifest order."""
    merged = {}     # env name -> spec
    owners = {}     # env name -> first service that set it
    for svc, entries in per_service_envs:
        for name, spec in entries:
            reason = policy.drop_reason(name)
            if reason:
                report["dropped"].setdefault(name, {"reason": reason, "services": []})
                report["dropped"][name]["services"].append(svc)
                continue
            if is_loopback(spec, bundled_chart_names):
                report["dropped"].setdefault(
                    name, {"reason": "loopback: callee is inside the bundle", "services": []})
                report["dropped"][name]["services"].append(svc)
                continue
            if name not in merged:
                merged[name] = spec
                owners[name] = svc
                continue
            if canon(merged[name]) == canon(spec):
                continue
            if name in policy.resolve or name in policy.contract_env:
                resolution = policy.resolve.get(name) or policy.contract_env[name]
                merged[name] = resolution
                report["resolved"].setdefault(name, {
                    "resolution": resolution, "between": [owners[name]]})
                if svc not in report["resolved"][name]["between"]:
                    report["resolved"][name]["between"].append(svc)
            else:
                report["conflicts"].setdefault(name, {
                    "kept": {"service": owners[name], "spec": merged[name]},
                    "ignored": []})
                report["conflicts"][name]["ignored"].append({"service": svc, "spec": spec})
    # Contract env wins over anything a member declared under the same name.
    for name, spec in policy.contract_env.items():
        merged[name] = copy.deepcopy(spec)
    return merged


