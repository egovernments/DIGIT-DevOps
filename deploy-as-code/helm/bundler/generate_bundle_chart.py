def emit_chart(out_dir, manifest_path, bundle, services, merged_env,
               db_migrations, contexts):
    banner = GENERATED_BANNER.format(manifest=manifest_path.name)
    out_dir.mkdir(parents=True, exist_ok=True)
    tpl_dir = out_dir / "templates"
    if tpl_dir.exists():
        shutil.rmtree(tpl_dir)
    tpl_dir.mkdir()

    chart_yaml = {
        "apiVersion": "v2",
        "name": bundle["name"],
        "description": ("GENERATED merged modulith bundle chart "
                        f"({', '.join(s['name'] for s in services)})"),
        "version": "0.1.0",
        "appVersion": str(bundle.get("version", "0.1.0")),
        "dependencies": [
            {"name": "common", "version": "0.0.5", "repository": "file://../../common"},
        ],
    }
    (out_dir / "Chart.yaml").write_text(
        banner + yaml.safe_dump(chart_yaml, sort_keys=False))

    values = {
        "labels": {"app": bundle["name"], "group": "core"},
        "image": {"repository": bundle["name"]},
        "replicas": 1,
        "appType": "java",
        "httpPort": int(bundle.get("port", 8080)),
        "heap": "-XX:InitialRAMPercentage=50.0 -XX:MaxRAMPercentage=75.0",
        "tracing-enabled": False,
        "healthChecks": {
            "enabled": False,
            "livenessProbePath": "/actuator/health/liveness",
            "readinessProbePath": "/actuator/health/readiness",
        },
        # One pod runs every bundled service; sized from the measured bundle
        # footprint, not the sum of the per-service charts.
        "resources": ("requests:\n"
                      "  cpu: \"500m\"\n"
                      "  memory: \"1Gi\"\n"
                      "limits:\n"
                      "  cpu: \"2\"\n"
                      "  memory: \"2Gi\"\n"),
        "ingress": {
            "enabled": True,
            "zuul": True,
            "contexts": contexts,
        },
        "env": merged_env,
        "dbMigrationOrder": [name for name, _ in db_migrations],
        "dbMigrations": {name: spec for name, spec in db_migrations},
    }
    values_header = banner + (
        "#\n"
        "# env is a MAP (name -> {value|valueFrom}); the environment values file\n"
        "# deep-merges it, so any single variable can be overridden (or removed by\n"
        f"# setting it to null) under the `{bundle['name']}:` block in\n"
        "# environments/<env>.yaml. Same for dbMigrations.<service>.image.tag.\n"
        "# JAVA_OPTS and SERVER_PORT are rendered from .Values.heap/.Values.httpPort.\n"
    )
    (out_dir / "values.yaml").write_text(
        values_header + yaml.safe_dump(values, sort_keys=False, width=100))

    (tpl_dir / "deployment.yaml").write_text(banner + DEPLOYMENT_TEMPLATE)
    (tpl_dir / "service.yaml").write_text(banner + SERVICE_TEMPLATE)
    (tpl_dir / "ingress.yaml").write_text(banner + INGRESS_TEMPLATE)


def emit_env_sample(out_dir, bundle, db_migrations):
    """A ready-to-paste block for environments/<env>.yaml."""
    lines = [
        f"# Sample environment override block for the {bundle['name']} chart —",
        "# paste into environments/<env>.yaml and fill in the image tags.",
        f"{bundle['name']}:",
        "  image:",
        f"    repository: {bundle['name']}",
        "    tag: \"<bundle-image-tag>\"",
        "  # Any single env var can be overridden (maps deep-merge):",
        "  # env:",
        "  #   DB_HOST: {value: \"postgres.egov\"}",
        "  #   TENANT_MIGRATION_ENABLED: {value: \"true\"}",
        "  #   FILESTORE_S3_SOURCE: {value: \"s3\"}    # flip a dev pin from the bundle jar",
        "  dbMigrations:",
    ]
    for name, spec in db_migrations:
        lines.append(f"    {name}:")
        lines.append(f"      image: {{repository: {spec['image']['repository']}, tag: \"<tag>\"}}")
    (out_dir / "env-block.sample.yaml").write_text("\n".join(lines) + "\n")


# ── report ───────────────────────────────────────────────────────────────────

def print_report(report, services, missing_migrations, context_mismatches):
    print("\n=== bundle chart generation report ===")
    print(f"services merged: {', '.join(s['name'] for s in services)}")
    if missing_migrations:
        print(f"no db-migration init container found for: {', '.join(missing_migrations)}")
    if context_mismatches:
        print("\nEXTERNAL PATH CHANGES — chart ingress.context vs manifest prefix")
        print("(Kong routes / clients using the old context must move to the manifest prefix):")
        for svc, chart_ctx, prefix in context_mismatches:
            print(f"  {svc}: chart served /{chart_ctx}, bundle serves {prefix}")
    if report["dropped"]:
        print(f"\ndropped env vars ({len(report['dropped'])}):")
        for name in sorted(report["dropped"]):
            info = report["dropped"][name]
            print(f"  {name}  [{', '.join(sorted(set(info['services'])))}]")
            print(f"      {info['reason']}")
    if report["resolved"]:
        print(f"\nconflicts resolved by rule ({len(report['resolved'])}):")
        for name, info in sorted(report["resolved"].items()):
            print(f"  {name}: {json.dumps(info['resolution'])}  "
                  f"(between {', '.join(info['between'])})")
    if report["conflicts"]:
        print(f"\nUNRESOLVED CONFLICTS ({len(report['conflicts'])}) — first-in-manifest-order won; "
              "add a `resolve:` entry to merge-rules.yaml (or `helm.resolve` in the manifest):")
        for name, info in sorted(report["conflicts"].items()):
            print(f"  {name}:")
            print(f"    kept   ({info['kept']['service']}): {json.dumps(info['kept']['spec'])}")
            for ig in info["ignored"]:
                print(f"    ignored ({ig['service']}): {json.dumps(ig['spec'])}")
    print("\nreminders:")
    print("  - remove the merged services from the Argo CD ApplicationSet and add the bundle entry")
    print("  - repoint egov-service-host keys for merged services at the bundle Service")
    print("  - Kong routes for the merged prefixes must target the bundle Service")


# ── main ─────────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--manifest", required=True, type=Path,
                    help="path to the digit3 bundle manifest (e.g. dev-bundle.package.yaml)")
    ap.add_argument("--charts-root", type=Path, default=DEFAULT_CHARTS_ROOT)
    ap.add_argument("--rules", type=Path, default=HERE / "merge-rules.yaml")
    ap.add_argument("--output", type=Path, default=None,
                    help="output chart dir (default charts/bundles/<bundle.name>)")
    args = ap.parse_args()

    manifest = load_yaml(args.manifest)
    bundle = manifest["bundle"]
    services = manifest["services"]
    policy = MergePolicy(load_yaml(args.rules), manifest.get("helm"))
    out_dir = args.output or (args.charts_root / "bundles" / bundle["name"])
    common_dir = args.charts_root / "common"
    if not (common_dir / "Chart.yaml").exists():
        die(f"common chart not found at {common_dir}")

    # Resolve every service to a chart before doing any work.
    resolved = []
    for svc in services:
        chart_dir = resolve_chart(args.charts_root, svc["name"])
        if chart_dir is None:
            die(f"no chart found for service '{svc['name']}' under {args.charts_root}")
        resolved.append((svc, chart_dir))
    bundled_chart_names = {chart_dir.name for _, chart_dir in resolved}

    report = {"dropped": {}, "resolved": {}, "conflicts": {}}
    per_service_envs = []
    db_migrations = []
    missing_migrations = []
    context_mismatches = []

    with tempfile.TemporaryDirectory(prefix="bundle-chart-") as scratch:
        scratch_root = Path(scratch)
        for svc, chart_dir in resolved:
            chart_values = load_yaml(chart_dir / "values.yaml") or {}
            deployment = render_deployment(chart_dir, common_dir, scratch_root)
            per_service_envs.append(
                (svc["name"], env_list_to_specs(extract_main_env(deployment, chart_dir.name))))

            prefix = svc.get("prefix", "/" + svc["name"])
            chart_ctx = ((chart_values.get("ingress") or {}).get("context") or "").strip("/")
            if chart_ctx and "/" + chart_ctx != prefix:
                context_mismatches.append((svc["name"], chart_ctx, prefix))

            mig = extract_db_migration(deployment)
            raw_mig = (chart_values.get("initContainers") or {}).get("dbMigration") or {}
            if mig is None or not raw_mig.get("enabled"):
                missing_migrations.append(svc["name"])
                continue
            mig_env = {name: spec for name, spec in env_list_to_specs(mig.get("env") or [])}
            db_migrations.append((svc["name"], {
                "enabled": True,
                "image": {
                    "repository": (raw_mig.get("image") or {}).get("repository",
                                                                   f"{chart_dir.name}-db"),
                    "tag": "",
                },
                "env": mig_env,
            }))

    merged_env = merge_envs(per_service_envs, policy, bundled_chart_names, report)
    contexts = [svc.get("prefix", "/" + svc["name"]).strip("/") for svc in services]

    emit_chart(out_dir, args.manifest, bundle, services, merged_env,
               db_migrations, contexts)
    emit_env_sample(out_dir, bundle, db_migrations)
    print(f"wrote {out_dir}")
    print_report(report, services, missing_migrations, context_mismatches)


if __name__ == "__main__":
    main()
